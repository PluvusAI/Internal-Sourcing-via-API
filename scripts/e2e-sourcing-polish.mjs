// Headless regression checks for archive navigation and the three-step sourcing editor.
// Usage: CHROMIUM_PATH=/path/to/chrome NODE_PATH=/path/to/playwright/node_modules node scripts/e2e-sourcing-polish.mjs http://127.0.0.1:5055
import { createRequire } from 'node:module';
import assert from 'node:assert/strict';
import { mkdirSync } from 'node:fs';
import { join } from 'node:path';
const { chromium } = createRequire(import.meta.url)('playwright');
const base = process.argv[2] ?? 'http://127.0.0.1:5055';
const shots = process.argv[3] ?? './artifacts/sourcing-redesign';
mkdirSync(shots, { recursive: true });
const browser = await chromium.launch(process.env.CHROMIUM_PATH ? { executablePath: process.env.CHROMIUM_PATH } : {});
const page = await browser.newPage({ viewport: { width: 1440, height: 1000 }, colorScheme: 'light' });
const errors = [];
page.on('pageerror', e => errors.push(e.message));
const tag = Date.now().toString(36);
const api = async (path, method = 'GET', body) => {
  const response = await fetch(`${base}/api${path}`, { method, headers: {'content-type':'application/json'}, ...(body ? {body: JSON.stringify(body)} : {}) });
  assert.ok(response.ok, `${method} ${path}: ${response.status}`);
  return response.json();
};
const shot = name => page.screenshot({path:join(shots,`${name}.png`),fullPage:true});
const noOverflow = async () => assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth), 'no horizontal page overflow');
try {
  console.log('• Archive while switching views; archived drafts stay disabled; restore updates both caches');
  const list = await api('/lists', 'POST', {name:`Archive ${tag}`,criteria:{platforms:[{platform:'instagram'}],niche:'Skincare routines'},targetCount:5});
  await page.goto(`${base}/?q=${encodeURIComponent(list.name)}`);
  await page.getByRole('link',{name:list.name,exact:true}).waitFor();
  let releaseArchive;
  const intercepted = new Promise(resolve => {
    page.route(`**/api/lists/${list.id}/archive`, async route => {
      await new Promise(release => { releaseArchive = release; resolve(); });
      await route.continue();
    }, {times:1});
  });
  await page.getByRole('button',{name:`Archive ${list.name}`,exact:true}).click();
  await intercepted;
  await page.getByRole('button',{name:'Archived',exact:true}).click();
  releaseArchive();
  await page.getByRole('button',{name:`Restore ${list.name}`,exact:true}).waitFor();
  assert.equal(await page.locator('.lists-table tbody tr').count(),1);
  await shot('after-library-archive');
  await page.getByRole('link',{name:list.name,exact:true}).click();
  await page.getByText('This list is archived',{exact:true}).waitFor();
  await page.getByRole('button',{name:/^Review & search/}).click();
  assert.ok(await page.getByRole('button',{name:'Find creators',exact:true}).isDisabled());
  assert.ok(await page.getByLabel('List name',{exact:true}).isDisabled());
  await page.getByRole('button',{name:'Restore list',exact:true}).click();
  await page.getByText('This list is archived',{exact:true}).waitFor({state:'detached'});
  await page.getByRole('link',{name:'Archived lists',exact:true}).click();
  await page.getByText('No matching lists',{exact:true}).waitFor();
  assert.equal(new URL(page.url()).searchParams.get('q'),list.name);
  assert.equal(new URL(page.url()).searchParams.get('archived'),'1');
  await page.getByRole('button',{name:'Active lists',exact:true}).click();
  await page.getByRole('link',{name:list.name,exact:true}).waitFor();
  await page.getByRole('button',{name:`Archive ${list.name}`,exact:true}).click();
  await page.getByRole('button',{name:'Undo',exact:true}).waitFor();
  await page.getByRole('button',{name:'Undo',exact:true}).click();
  await page.getByRole('link',{name:list.name,exact:true}).waitFor();
  console.log('• Archiving the only row on the final page returns to the previous page');
  const prefix=`Pagination ${tag}`;
  await Promise.all(Array.from({length:26},(_,i)=>api('/lists','POST',{name:`${prefix} ${i}`})));
  await page.goto(`${base}/?q=${encodeURIComponent(prefix)}&page=2`);
  await page.getByRole('button',{name:/^Archive Pagination/}).waitFor();
  await page.getByRole('button',{name:/^Archive Pagination/}).click();
  await page.waitForURL(url=>url.searchParams.get('page')===null);
  await page.getByText(`25 lists match “${prefix}”`,{exact:true}).waitFor();
  assert.equal(await page.locator('.lists-table tbody tr').count(),25);
  console.log('• Criteria validation, suggestions, step Back/Forward, reload, exclusions and review');
  const draft=await api('/lists','POST',{name:`Luma — Skincare creators ${tag}`,targetCount:5});
  await page.goto(`${base}/lists/${draft.id}?from=${encodeURIComponent('/?q=Luma')}`);
  await page.getByRole('heading',{name:'Define your ideal creators'}).waitFor();
  await page.getByRole('button',{name:'Continue to exclusions'}).click();
  await page.getByText('Choose at least one platform.',{exact:true}).waitFor();
  await page.getByRole('checkbox',{name:'Instagram',exact:true}).check();
  await page.getByLabel('Short brief').fill('Skincare creators explaining gentle daily routines for sensitive skin.');
  await page.getByRole('button',{name:'Suggest criteria',exact:true}).click();
  await page.locator('.criteria-field .suggested-label').first().waitFor();
  const suggestedNiche=await page.getByLabel('Niche / search query',{exact:true}).inputValue();
  assert.ok(suggestedNiche.length>=3);
  await page.getByLabel('Niche / search query',{exact:true}).fill('Skincare routines');
  await page.getByLabel('Min followers',{exact:true}).fill('10000');
  await page.getByLabel('Max followers',{exact:true}).fill('100000');
  await page.getByText('Saved',{exact:true}).waitFor();
  await shot('after-criteria');
  await page.getByRole('button',{name:'Continue to exclusions'}).click();
  await page.getByRole('heading',{name:'Exclude creators from these lists'}).waitFor();
  await shot('after-exclusions');
  await page.goBack();
  await page.getByRole('heading',{name:'Define your ideal creators'}).waitFor();
  assert.equal(await page.getByLabel('Niche / search query').inputValue(),'Skincare routines');
  await page.goForward();
  await page.getByRole('button',{name:'Continue to review'}).click();
  await page.getByRole('heading',{name:'Review & start the search'}).waitFor();
  await page.getByText('10,000–100,000 followers',{exact:true}).waitFor();
  await page.reload();
  await page.getByRole('heading',{name:'Review & start the search'}).waitFor();
  await shot('after-review');
  assert.equal((await api(`/lists/${draft.id}`)).operations.length,0,'navigation and reload never start sourcing');
  const meta=await api('/meta');
  await page.getByLabel('New qualifying creators to find').fill(String(meta.maxTargetCount+1));
  await page.getByText(`At most ${meta.maxTargetCount} new creators per search`).waitFor();
  assert.ok(await page.getByRole('button',{name:'Find creators',exact:true}).isDisabled());
  await page.getByLabel('New qualifying creators to find').fill('5');
  await page.getByText('Saved',{exact:true}).waitFor();
  for (const colorScheme of ['light','dark']) {
    await page.emulateMedia({colorScheme});
    await page.setViewportSize({width:390,height:844});
    await noOverflow();
    await shot(`review-mobile-${colorScheme}`);
    await page.getByRole('button',{name:/^Criteria/}).click();
    await page.getByRole('heading',{name:'Define your ideal creators'}).waitFor();
    await noOverflow();
    await shot(`criteria-mobile-${colorScheme}`);
    await page.getByRole('button',{name:/^Review & search/}).click();
  }
  await page.setViewportSize({width:1440,height:1000});
  await page.emulateMedia({colorScheme:'light'});
  await page.getByRole('link',{name:'All lists',exact:true}).click();
  await page.getByRole('heading',{name:'Creator lists',exact:true}).waitFor();
  await shot('after-library');
  assert.equal(new URL(page.url()).searchParams.get('q'),'Luma');
  assert.deepEqual(errors,[]);
  console.log('✓ sourcing polish regression passed');
} catch (error) {
  await shot('regression-failure').catch(()=>{});
  console.error(error);
  process.exitCode=1;
} finally { await browser.close(); }
